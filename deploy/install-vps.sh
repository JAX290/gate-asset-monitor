#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Idempotent installer for a Tailscale-only VPS deployment.
#
# Run ON the VPS, as root, from anywhere:
#   bash /opt/gate-asset-monitor/deploy/install-vps.sh
#
# What it touches (and nothing else):
#   - /opt/gate-asset-monitor/              project + private Node runtime
#   - /etc/systemd/system/gate-asset-monitor.service
# It does NOT touch Caddy, nginx, existing Docker containers, firewall rules,
# SSH config, or any other systemd unit. Safe to run alongside live services.
# ---------------------------------------------------------------------------
set -euo pipefail

APP_DIR="${APP_DIR:-/opt/gate-asset-monitor}"
SERVICE="gate-asset-monitor"
NODE_VERSION="${NODE_VERSION:-v24.22.3}"
PORT="${PORT:-8787}"

log() { echo "==> $*"; }

log "[1/7] preflight"
[ "$(id -u)" -eq 0 ] || { echo "must run as root" >&2; exit 1; }
[ -f "$APP_DIR/src/server.js" ] || { echo "project not found at $APP_DIR" >&2; exit 1; }
command -v curl >/dev/null || { echo "curl required" >&2; exit 1; }
command -v openssl >/dev/null || { echo "openssl required" >&2; exit 1; }
command -v systemctl >/dev/null || { echo "systemd required" >&2; exit 1; }
TAILSCALE_BIN="$(command -v tailscale || echo /usr/bin/tailscale)"
[ -x "$TAILSCALE_BIN" ] || { echo "tailscale CLI required" >&2; exit 1; }
TS_IP="$("$TAILSCALE_BIN" ip -4 | head -n1 | tr -d '[:space:]')"
[ -n "$TS_IP" ] || { echo "Tailscale IPv4 not ready" >&2; exit 1; }
echo "    node=$(uname -m)  tailscale_ip=$TS_IP  port=$PORT"

# Normalise line endings if the project was transferred from a Windows host.
find "$APP_DIR/deploy" -type f -name '*.sh' -exec sed -i 's/\r$//' {} + 2>/dev/null || true
chmod +x "$APP_DIR/deploy/"*.sh
mkdir -p "$APP_DIR/data"

log "[2/7] private Node runtime (no system packages installed)"
RUNTIME="$APP_DIR/.runtime"
NODE_BIN="$RUNTIME/node/bin/node"
if [ -x "$NODE_BIN" ]; then
  echo "    already present: $("$NODE_BIN" -v)"
else
  case "$(uname -m)" in
    x86_64)  NODE_ARCH="linux-x64" ;;
    aarch64) NODE_ARCH="linux-arm64" ;;
    *) echo "unsupported arch: $(uname -m)" >&2; exit 1 ;;
  esac
  TARBALL="node-$NODE_VERSION-$NODE_ARCH.tar.xz"
  URL="https://nodejs.org/dist/$NODE_VERSION/$TARBALL"
  echo "    downloading $URL"
  mkdir -p "$RUNTIME"
  curl -fsSL --retry 3 --connect-timeout 15 -o "/tmp/$TARBALL" "$URL"
  tar -xJf "/tmp/$TARBALL" -C "$RUNTIME"
  rm -rf "$RUNTIME/node"
  mv "$RUNTIME/node-$NODE_VERSION-$NODE_ARCH" "$RUNTIME/node"
  rm -f "/tmp/$TARBALL"
  echo "    installed $("$NODE_BIN" -v)"
fi

log "[3/7] port check"
if ss -tln 2>/dev/null | grep -qE ":${PORT}\b"; then
  echo "    WARNING: port $PORT already has a listener:" >&2
  ss -tlnp 2>/dev/null | grep -E ":${PORT}\b" >&2 || true
else
  echo "    port $PORT is free"
fi

log "[4/7] .env (created once, never overwritten)"
ENV_FILE="$APP_DIR/.env"
if [ -f "$ENV_FILE" ]; then
  echo "    existing .env preserved"
  grep -q '^TAILSCALE_ONLY=true' "$ENV_FILE" || echo "TAILSCALE_ONLY=true" >> "$ENV_FILE"
else
  TOKEN="$(openssl rand -hex 24)"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by install-vps.sh -- keep private.
DATA_MODE=mock
PORT=$PORT
TAILSCALE_ONLY=true
ACCESS_TOKEN=$TOKEN
SNAPSHOT_INTERVAL_SEC=300
RETENTION_DAYS=365
QUOTE_LABEL=USD
GATE_API_KEY=
GATE_API_SECRET=
EOF
  chmod 600 "$ENV_FILE"
  echo "    generated ACCESS_TOKEN=$TOKEN"
fi

log "[5/7] systemd unit"
UNIT="/etc/systemd/system/$SERVICE.service"
cat > "$UNIT" <<EOF
[Unit]
Description=Gate Asset Monitor (Tailscale only)
After=network-online.target tailscaled.service
Wants=network-online.target
Requires=tailscaled.service

[Service]
Type=simple
WorkingDirectory=$APP_DIR
EnvironmentFile=$ENV_FILE
ExecStart=$APP_DIR/deploy/start-tailscale.sh
Restart=on-failure
RestartSec=5

# Hardening (kept moderate so the tailscale CLI socket stays reachable)
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
ProtectHome=true
ReadWritePaths=$APP_DIR/data
CapabilityBoundingSet=
AmbientCapabilities=

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload

log "[6/7] enable + start"
systemctl enable "$SERVICE" >/dev/null 2>&1 || true
systemctl restart "$SERVICE"
sleep 2
systemctl --no-pager --lines=12 status "$SERVICE" || true

log "[7/7] done"
echo ""
echo "  Dashboard (Tailscale only):  http://$TS_IP:$PORT"
echo "  Existing services untouched (Caddy / Docker / firewall unchanged)."
echo "  Logs:  journalctl -u $SERVICE -f"
echo "  Verify: bash $APP_DIR/deploy/verify-tailscale.sh"
echo ""
